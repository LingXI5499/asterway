-- 按会话 ID 锁定目标；无外键级联时，先显式清理属性，再删除父会话。
WITH target AS MATERIALIZED (
    SELECT PRIMARY_ID FROM %TABLE_NAME% WHERE SESSION_ID = ? FOR UPDATE
), attributes AS (
    DELETE FROM %TABLE_NAME%_ATTRIBUTES a USING target t
    WHERE a.SESSION_PRIMARY_ID = t.PRIMARY_ID RETURNING 1
)
DELETE FROM %TABLE_NAME% s USING target t
WHERE s.PRIMARY_ID = t.PRIMARY_ID AND (SELECT COUNT(*) FROM attributes) >= 0
