-- 先锁定父会话，再写入属性；父会话已删除时不创建孤立属性。
-- %TABLE_NAME% 由 Spring Session 替换，问号参数顺序遵循其 JDBC 绑定契约。
WITH parent AS (
    SELECT PRIMARY_ID FROM %TABLE_NAME% WHERE PRIMARY_ID = ? FOR UPDATE
)
INSERT INTO %TABLE_NAME%_ATTRIBUTES (SESSION_PRIMARY_ID, ATTRIBUTE_NAME, ATTRIBUTE_BYTES)
SELECT parent.PRIMARY_ID, ?, ? FROM parent
ON CONFLICT (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
DO UPDATE SET ATTRIBUTE_BYTES = EXCLUDED.ATTRIBUTE_BYTES
