function build(entries: Entry[], group: string, category: Category): GrowthTemplate[] {
  return entries.map(([id, title, audience, days, description, stages, actions]) => ({
    id,
    title,
    audience,
    days,
    description,
    stages,
    actions,
    group,
    category,
    tags: [group, audience],
    habit:
      group === '运动与生活'
        ? '每天记录一个生活小改变'
        : group === '创作与阅读'
          ? '每天记录一个灵感或收获'
          : '每天留出 20 分钟练习',
  }));
}
